#!/usr/bin/env node
/**
 * Writes src/agents/catalog.generated.ts from ui/src/api.ts: every Studio API call the screens make
 * (name, method, path, arguments, body, result type) and the type definitions they use, so agents can
 * do whatever a screen does. Run after changing ui/src/api.ts (a test checks it is up to date).
 */
const fs = require('fs');
const path = require('path');
const root = path.join(__dirname, '..');
const src = fs.readFileSync(path.join(root, 'ui/src/api.ts'), 'utf8');

function catalog(text) {
    const calls = [];
    const re = /^ {4}(\w+): \((.*?)\) => request(?:<(.+?)>)?\('(GET|POST|PUT|DELETE|PATCH)', (.+?)\),?\s*$/;
    for (const line of text.split('\n')) {
        const m = re.exec(line);
        if (!m) continue;
        const [, name, args, result, method, rest] = m;
        // The path (template parts as :name) and the body expression.
        let p = '', body = '';
        const t = /^`([^`]*)`(.*)$/.exec(rest) || /^'([^']*)'(.*)$/.exec(rest);
        if (!t) continue;
        p = t[1].replace(/\$\{encodeURIComponent\((\w+)[^}]*\}/g, ':$1').replace(/\$\{(\w+)\}/g, ':$1');
        let tail = t[2].trim();
        let query = '';
        const qm = /^\+ q\((.*?)\)(?:,|$)\s*(.*)$/.exec(tail);
        if (qm) { query = qm[1]; tail = qm[2]; }
        if (tail.startsWith(',')) tail = tail.slice(1).trim();
        // A screen's AbortSignal (cancel a request when the person typed on) is not part of the call.
        body = tail.replace(/,\s*signal\s*$/, '');
        const callArgs = args.replace(/,\s*signal\?: AbortSignal/, '');
        const area = (p.split('/')[2] || '').replace(/[^a-z-]/gi, '');
        // Areas agents may not call (tools.ts BLOCKED): not offered.
        if (['agents', 'mcp', 'missions', 'evals', 'agent-builder', 'inbox'].includes(area)) continue;
        calls.push({ name, area, method, path: p, args: callArgs, ...(query ? { query } : {}), ...(body ? { body } : {}), result: result || 'unknown' });
    }
    const types = {};
    const lines = text.split('\n');
    for (let i = 0; i < lines.length; i++) {
        const m = /^export (?:interface|type) (\w+)/.exec(lines[i]);
        if (!m) continue;
        let j = i, depth = 0, out = [];
        for (; j < lines.length; j++) {
            out.push(lines[j]);
            depth += (lines[j].match(/\{/g) || []).length - (lines[j].match(/\}/g) || []).length;
            if (depth <= 0 && (/[;}]\s*$/.test(lines[j]) || /^export type .*;$/.test(lines[j]))) break;
        }
        types[m[1]] = out.join('\n').slice(0, 4000);
    }
    return { calls, types };
}

const c = catalog(src);
const out = `/* Generated by scripts/gen-agent-catalog.js from ui/src/api.ts: do not edit. */
export interface CatalogCall { name: string; area: string; method: string; path: string; args: string; query?: string; body?: string; result: string }
export const CALLS: CatalogCall[] = ${JSON.stringify(c.calls, null, 1)};
export const TYPES: Record<string, string> = ${JSON.stringify(c.types, null, 1)};
`;
const file = path.join(root, 'src/agents/catalog.generated.ts');
if (process.argv.includes('--check')) {
    const now = fs.existsSync(file) ? fs.readFileSync(file, 'utf8') : '';
    if (now !== out) { console.error('src/agents/catalog.generated.ts is out of date: run node scripts/gen-agent-catalog.js'); process.exit(1); }
    console.log('catalog up to date');
} else {
    fs.writeFileSync(file, out);
    console.log(`${c.calls.length} calls, ${Object.keys(c.types).length} types`);
}
module.exports = { catalog };

/**
 * Load tests in Azure DevOps: a pipeline (YAML) for a scenario, and the summary a run shows on its page.
 *  - Plan: one start time for every load generator (a few minutes ahead, so all agents are ready).
 *  - Generate: N parallel jobs (agents from the pool, e.g. scale-set agents started on demand), each running its
 *    part of the users from the repository's own node_modules, starting at the planned time.
 *  - Report: the parts merged exactly; compared with the last successful run of the branch (the regression gate);
 *    service levels and the gate as test results; HTML, PDF and Word reports and the merged results published as
 *    the "load-results" artifact (the Studio imports it from there); a summary on the run's page; optionally the run
 *    shared with the team folder.
 * A nightly schedule is a cron line; secrets come from a variable group as environment variables ({env:NAME}).
 */
import * as path from 'path';
import type { LoadRunDetail } from './runs';
import { describePolicy } from './policy';
import { runInsights } from './insights';

/** A run name as an Azure DevOps build number: without the characters it refuses (" / : < > \\ | ? @ *). */
const buildName = (n: string) => n.replace(/["/:<>\\|?@*]/g, ' ').replace(/\s+/g, ' ').trim().replace(/\.+$/, '').slice(0, 200) || 'Tests';

export interface LoadPipelineOptions {
    name: string; envs: string[]; generators?: number; schedule?: string; variableGroup?: string; secretNames?: string[];
    branch?: string; pool?: string; nodeVersion?: string; teamFolder?: string; startDelayMinutes?: number;
}

const q = (s: string) => `'${s.replace(/'/g, "''")}'`;

export function loadPipeline(file: string, o: LoadPipelineOptions): string {
    const envs = o.envs.length ? o.envs : ['dev'];
    const gens = Math.max(1, Math.min(o.generators ?? 1, 50));
    const secretEnv = (o.secretNames ?? []).filter((n) => /^[A-Za-z_][\w]*$/.test(n));
    const env = secretEnv.length ? `\n        env:\n${secretEnv.map((n) => `          ${n}: $(${n})`).join('\n')}` : '';
    const pool = o.pool ? `\n    pool:\n      name: ${q(o.pool)}` : '\n    pool:\n      vmImage: ubuntu-latest';
    const node = `      - task: UseNode@1\n        inputs:\n          version: ${q(o.nodeVersion ?? '20.x')}\n      - script: npm ci\n        displayName: Install`;
    return [
        `# ${o.name}: the load test ${file}, run by CS Test Studio on ${gens > 1 ? `${gens} load generators in parallel` : 'one agent'}.`,
        '# Generated by CS Test Studio (Performance → the scenario → ⋯ → Azure DevOps pipeline).',
        `name: ${q(`${buildName(o.name)} $(Date:yyyyMMdd)$(Rev:.r)`)}`,
        '',
        'trigger: none',
        ...(o.schedule ? ['', `schedules:\n  - cron: ${q(o.schedule)}\n    displayName: ${q(`${o.name} (nightly)`)}\n    branches:\n      include: [${o.branch ?? 'main'}]\n    always: true`] : []),
        '',
        `parameters:\n  - name: environment\n    displayName: Environment\n    type: string\n    default: ${envs[0]}\n    values: [${envs.join(', ')}]\n  - name: generators\n    displayName: Load generators (parallel jobs)\n    type: number\n    default: ${gens}`,
        '',
        `variables:${o.variableGroup ? `\n  - group: ${q(o.variableGroup)}` : ''}\n  - name: results\n    value: $(Pipeline.Workspace)/load`,
        '',
        'stages:',
        '  - stage: Load',
        '    jobs:',
        '      - job: Plan',
        '        displayName: Plan the common start',
        `        pool:\n          vmImage: ubuntu-latest`,
        '        steps:',
        '          - checkout: none',
        `          - bash: echo "##vso[task.setvariable variable=startAt;isOutput=true]$(date -u -d '+${o.startDelayMinutes ?? 4} minutes' +%Y-%m-%dT%H:%M:%SZ)"\n            name: when\n            displayName: Start time`,
        '',
        '      - job: Generate',
        '        displayName: Load generator',
        '        dependsOn: Plan',
        '        strategy:\n          parallel: ${{ parameters.generators }}',
        `        timeoutInMinutes: 360`,
        `        variables:\n          startAt: $[ dependencies.Plan.outputs['when.startAt'] ]`,
        `${pool.replace(/\n {4}/g, '\n        ')}`,
        '        steps:',
        '          - checkout: self',
        node.replace(/^ {6}/gm, '          '),
        `          - script: >-\n              npx cs-test-studio load ${q(file)}\n              --env \${{ parameters.environment }}\n              --part $(System.JobPositionInPhase)/$(System.TotalJobsInPhase)\n              --start-at $(startAt)\n              --json $(results)/part-$(System.JobPositionInPhase).json\n            displayName: Run my part of the users${env.replace(/\n {8}/g, '\n            ')}`,
        `          - publish: $(results)\n            artifact: load-part-$(System.JobPositionInPhase)\n            condition: succeededOrFailed()`,
        '',
        '      - job: Report',
        '        displayName: Merge, compare, report',
        '        dependsOn: Generate',
        '        condition: succeededOrFailed()',
        `        pool:\n          vmImage: ubuntu-latest`,
        '        steps:',
        '          - checkout: self',
        node.replace(/^ {6}/gm, '          '),
        `          - download: current\n            patterns: 'load-part-*/*.json'`,
        '          # The last successful run of this branch: the baseline of the regression gate (none the first time).',
        `          - task: DownloadPipelineArtifact@2\n            displayName: Baseline (last successful run)\n            continueOnError: true\n            inputs:\n              source: specific\n              project: $(System.TeamProjectId)\n              pipeline: $(System.DefinitionId)\n              runVersion: latestFromBranch\n              runBranch: $(Build.SourceBranch)\n              artifact: load-results\n              path: $(Pipeline.Workspace)/baseline`,
        `          - bash: |\n              set -e\n              mkdir -p $(results)\n              parts=$(ls $(Pipeline.Workspace)/load-part-*/*.json)\n              base=""; [ -f "$(Pipeline.Workspace)/baseline/results.json" ] && base="--baseline $(Pipeline.Workspace)/baseline/results.json"\n              if [ $(echo "$parts" | wc -w) -gt 1 ]; then cmd="npx cs-test-studio load-merge $parts"; else cmd="npx cs-test-studio load-report $parts"; fi\n              $cmd $base --json $(results)/results.json --junit $(results)/junit.xml --html $(results)/report.html --pdf $(results)/report.pdf --docx $(results)/report.docx --summary $(results)/summary.md${o.teamFolder ? ` --team ${q(o.teamFolder)}` : ''}\n            displayName: Merge and check`,
        `          - bash: echo "##vso[task.uploadsummary]$(results)/summary.md"\n            displayName: Summary on the run page\n            condition: succeededOrFailed()`,
        `          - task: PublishTestResults@2\n            condition: succeededOrFailed()\n            inputs:\n              testResultsFormat: JUnit\n              testResultsFiles: $(results)/junit.xml\n              testRunTitle: ${q(`${o.name} (\${{ parameters.environment }})`)}\n              failTaskOnFailedTests: true`,
        `          - publish: $(results)\n            artifact: load-results\n            condition: succeededOrFailed()`,
        '',
    ].join('\n');
}

/** A short Markdown summary of a run (the pipeline run's Summary tab, a PR comment, a chat message). */
export function loadSummaryMarkdown(d: LoadRunDetail): string {
    const r = d.result;
    if (!r) return `**${d.name}**: no results${d.message ? ` (${d.message})` : ''}.`;
    const cell = (s: unknown) => String(s).replace(/\|/g, '\\|').replace(/\n/g, ' ');
    const lines = [
        `## ${r.passed ? '✅' : '❌'} ${cell(d.name)} — ${r.passed ? 'passed' : 'failed'}`,
        '',
        `${cell(d.env)} · ${cell(describePolicy(d.definition.policy))} · ${Math.round(r.elapsed)} s${r.part ? '' : ''}${r.stopReason !== 'completed' ? ` · stopped: ${r.stopReason}` : ''}`,
        '',
        '| Requests | Errors | Average | 95% | 99% | Per second |',
        '|---:|---:|---:|---:|---:|---:|',
        `| ${r.total.count} | ${r.total.errorRate.toFixed(2)}% | ${r.total.avg} ms | ${r.total.p95} ms | ${r.total.p99} ms | ${r.total.throughput.toFixed(1)} |`,
    ];
    lines.push('', runInsights(r).summary);
    if (r.slas.length) lines.push('', '| Service level | Result | Details |', '|---|---|---|', ...r.slas.map((s) => `| ${cell(s.name)} | ${!s.pass ? '❌ missed' : s.level === 'warning' ? '⚠️ warning' : '✅ met'} | ${cell(s.details.join('; '))} |`));
    const slow = [...r.transactions].sort((a, b) => b.p95 - a.p95).slice(0, 10);
    if (slow.length) lines.push('', '| Transaction | Count | Errors | 95% |', '|---|---:|---:|---:|', ...slow.map((t) => `| ${cell(t.name)} | ${t.count} | ${t.errorRate.toFixed(2)}% | ${t.p95} ms |`));
    if ((r.alerts ?? []).length) lines.push('', `**Alerts:** ${r.alerts.slice(0, 5).map((a) => cell(a.message)).join(' · ')}`);
    if (r.overload) lines.push('', `⚠️ ${cell(r.overload)}`);
    lines.push('', `_Reports in the **load-results** artifact (${path.basename('report.html')}, PDF, Word)._`);
    return lines.join('\n') + '\n';
}
